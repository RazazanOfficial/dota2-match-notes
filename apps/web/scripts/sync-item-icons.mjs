import { mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const CONSTANTS_URL = "https://api.opendota.com/api/constants/items";
const CDN_ORIGIN = "https://cdn.cloudflare.steamstatic.com";
const projectRoot = process.cwd();
const outputDirectory = path.join(projectRoot, "public", "items");
const catalogPath = path.join(projectRoot, "data", "items.generated.ts");

const constants = process.env.ITEM_CONSTANTS_FILE
  ? JSON.parse(await readFile(process.env.ITEM_CONSTANTS_FILE, "utf8"))
  : await fetchItemConstants();
if (!constants || typeof constants !== "object" || Array.isArray(constants)) {
  throw new Error("OpenDota item constants are not an object");
}

const items = Object.entries(constants)
  .map(([key, raw]) => normalizeItem(key, raw))
  .filter((item) => item !== null)
  .sort((left, right) => left.id - right.id);

if (items.length < 300 || new Set(items.map((item) => item.id)).size !== items.length) {
  throw new Error("Item catalog is incomplete or contains duplicate IDs");
}

await mkdir(outputDirectory, { recursive: true });

const uniqueImages = [...new Map(items.map((item) => [item.slug, item.sourceUrl])).entries()];
if (process.env.ITEMS_CATALOG_ONLY !== "1") {
  let cursor = 0;
  const workers = Array.from({ length: Math.min(12, uniqueImages.length) }, async () => {
    while (cursor < uniqueImages.length) {
      const index = cursor;
      cursor += 1;
      const [slug, sourceUrl] = uniqueImages[index];
      await downloadImage(slug, sourceUrl);
    }
  });
  await Promise.all(workers);
}

const catalog = `// Generated by scripts/sync-item-icons.mjs. Do not edit manually.\n\n` +
  `export interface DotaItem {\n  id: number;\n  slug: string;\n  name: string;\n}\n\n` +
  `export const DOTA_ITEMS = ${JSON.stringify(
    items.map(({ id, slug, name }) => ({ id, slug, name })),
    null,
    2,
  )} as const satisfies readonly DotaItem[];\n\n` +
  `const ITEM_BY_ID = new Map<number, DotaItem>(DOTA_ITEMS.map((item) => [item.id, item] as const));\n\n` +
  `export function itemById(id: number) {\n  return ITEM_BY_ID.get(id);\n}\n\n` +
  `export function itemImage(id: number) {\n  const item = itemById(id);\n  return item ? \`/items/\${item.slug}.png\` : null;\n}\n`;

await writeFile(catalogPath, catalog, "utf8");

if (process.env.ITEMS_CATALOG_ONLY !== "1") {
  for (const [slug] of uniqueImages) {
    const details = await stat(path.join(outputDirectory, `${slug}.png`));
    if (!details.isFile() || details.size < 256) {
      throw new Error(`Item icon verification failed: ${slug}`);
    }
  }
}

console.log(
  process.env.ITEMS_CATALOG_ONLY === "1"
    ? `Generated the catalog for ${items.length} item IDs.`
    : `Synchronized ${uniqueImages.length} local item icons for ${items.length} item IDs.`,
);

async function fetchItemConstants() {
  const response = await fetch(CONSTANTS_URL, {
    headers: { Accept: "application/json", "User-Agent": "Dota2MatchNotes/1.0" },
  });
  if (!response.ok) {
    throw new Error(`Unable to download item constants (${response.status})`);
  }
  return response.json();
}

function normalizeItem(key, raw) {
  if (!raw || typeof raw !== "object") return null;
  const id = Number(raw.id);
  const imagePath = typeof raw.img === "string" ? raw.img.split("?", 1)[0] : "";
  const imageFile = imagePath.split("/").at(-1) || "";
  const slug = imageFile.endsWith(".png") ? imageFile.slice(0, -4) : "";
  if (!Number.isInteger(id) || id <= 0 || !/^[a-z0-9_]+$/.test(slug)) return null;
  return {
    id,
    slug,
    name: typeof raw.dname === "string" && raw.dname.trim() ? raw.dname.trim() : key,
    sourceUrl: new URL(imagePath, CDN_ORIGIN).toString(),
  };
}

async function downloadImage(slug, sourceUrl) {
  const destination = path.join(outputDirectory, `${slug}.png`);
  const temporary = `${destination}.download`;
  const response = await fetch(sourceUrl, {
    headers: { Accept: "image/png", "User-Agent": "Dota2MatchNotes/1.0" },
  });
  if (!response.ok) {
    throw new Error(`Unable to download item icon: ${slug} (${response.status})`);
  }
  const contentType = response.headers.get("content-type")?.split(";", 1)[0];
  if (contentType !== "image/png" && contentType !== "application/octet-stream") {
    throw new Error(`Unexpected item icon content type for ${slug}: ${contentType}`);
  }
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.byteLength < 256 || bytes.byteLength > 1_572_864) {
    throw new Error(`Unexpected item icon size for ${slug}: ${bytes.byteLength}`);
  }
  await writeDownload(temporary, bytes);
  await rename(temporary, destination);
}

async function writeDownload(filePath, bytes) {
  try {
    await writeFile(filePath, bytes, { flag: "wx" });
  } catch (error) {
    if (error && typeof error === "object" && error.code === "EEXIST") {
      await rm(filePath, { force: true });
      await writeFile(filePath, bytes, { flag: "wx" });
      return;
    }
    throw error;
  }
}
